-- criterion_id codes required by the organizers' results.json (Appendix "Как сдать результаты")
ALTER TABLE criterion ADD COLUMN export_id TEXT;
UPDATE criterion k SET export_id = m.eid
FROM (VALUES ('C01','contact'),('C02','discovery'),('C03','identification'),('C04','consultation'),
             ('C05','empathy'),('C06','dialogue'),('C07','closure'),('C08','critical')) AS m(code, eid)
WHERE k.code = m.code;
UPDATE criterion SET export_id = lower(code) WHERE export_id IS NULL;
ALTER TABLE criterion ALTER COLUMN export_id SET NOT NULL;

